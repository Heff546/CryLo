'use strict';

// Verify exactly the staged helper NSIS will embed and its generated hash pin.
// This is complementary to NSIS certutil/findstr validation at installation.
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const STAGE = 'crylo-installer-helper-staged';
const DEFINE = 'CRYLO_INSTALLER_HELPER_SHA256';

function regular(file) {
  const st = fs.lstatSync(file);
  if (!st.isFile() || st.isSymbolicLink()) {
    throw new Error('CryLo NSIS trust input is not a regular file: ' + file);
  }
  return fs.readFileSync(file);
}

function canonical(bytes) {
  const text = bytes.toString('utf8');
  if (!Buffer.from(text, 'utf8').equals(bytes) || text.replace(/\r\n/g, '').includes('\r')) {
    throw new Error('CryLo installer helper must be UTF-8 without lone CR.');
  }
  return Buffer.from(text.replace(/\r\n/g, '\n'), 'utf8');
}

function verifyWindowsInstallerHelperPin(electronDir, options = {}) {
  const build = path.join(electronDir, 'build');
  const source = options.helperPath || path.join(build, 'windows-installer-runtime.js');
  const nsis = options.nsisPath || path.join(build, 'installer.nsh');
  const stage = path.join(build, STAGE);
  const staged = options.stagedPath || path.join(stage, 'windows-installer-runtime.js');
  const pin = options.pinPath || path.join(stage, 'helper-sha256.generated.nsh');

  const src = canonical(regular(source));
  const installed = regular(staged);
  if (!src.equals(installed)) {
    throw new Error('Windows NSIS helper staging differs from canonical source.');
  }
  const actual = crypto.createHash('sha256').update(installed).digest('hex');
  const pinText = regular(pin).toString('ascii');
  const expectedPin = '; Generated by CryLo before-pack.js from the committed helper bytes.\r\n' +
    `!define ${DEFINE} "${actual}"\r\n`;
  if (pinText !== expectedPin) {
    throw new Error('Windows NSIS helper SHA256 mismatch in generated trust pin.');
  }
  const text = regular(nsis).toString('utf8');
  const expectedInclude = '!include "${BUILD_RESOURCES_DIR}\\' + STAGE + '\\helper-sha256.generated.nsh"';
  const expectedEmbed = 'File /oname=$PLUGINSDIR\\windows-installer-runtime.js ' +
    '"${BUILD_RESOURCES_DIR}\\' + STAGE + '\\windows-installer-runtime.js"';
  const expectedCompare = '/C:"${' + DEFINE + '}"';
  for (const term of [expectedInclude, expectedEmbed, expectedCompare]) {
    if (text.split(term).length !== 2) {
      throw new Error('Windows NSIS helper trust reference missing or duplicated: ' + term);
    }
  }
  const section = text.match(/StrCpy \$R9 "HELPER_HASH_COMPARE"[\s\S]*?StrCmp \$R0 "0" crylo_helper_verified crylo_runtime_failed/);
  if (!section || !section[0].includes(expectedCompare)) {
    throw new Error('Windows NSIS helper hash compare does not use the generated pin.');
  }
  console.log('PASS: Windows NSIS generated helper SHA256 ' + actual);
  return actual;
}

module.exports = Object.freeze({ verifyWindowsInstallerHelperPin });

if (require.main === module) {
  try {
    const electronDir = path.resolve(__dirname, '..');
    // Existing CI preflight entrypoint also generates and authenticates the pin.
    require('./before-pack').stageWindowsInstallerHelper(electronDir);
    verifyWindowsInstallerHelperPin(electronDir);
  } catch (error) {
    console.error('ERROR: ' + error.message);
    process.exitCode = 1;
  }
}
